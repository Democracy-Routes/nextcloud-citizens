/** The done screen of a Record now session says the report comes by itself. */
import { flushPromises } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import RecordingScreen from '../../frontend/src/recorder/components/RecordingScreen.vue'
import { mountWithI18n } from './support/mount'

const status = vi.fn()
const shared = vi.hoisted(() => ({ state: {} as Record<string, unknown> }))
const finish = vi.fn().mockResolvedValue(undefined)

vi.mock('../../frontend/src/recorder/api', async () => {
	const actual = await vi.importActual<Record<string, unknown>>('../../frontend/src/recorder/api')
	return {
		...actual,
		recorderApi: {
			status: (...a: unknown[]) => status(...a),
			liveTranscript: vi.fn().mockResolvedValue({ lines: [] }),
		},
	}
})
vi.mock('../../frontend/src/recorder/useWakeLock', async () => {
	const { ref } = await import('vue')
	return {
		useWakeLock: () => ({ held: ref(true), supported: true }),
		wakeLockHeld: ref(true),
	}
})
vi.mock('../../frontend/src/recorder/idb', () => ({ idb: {} }))
vi.mock('../../frontend/src/recorder/engine', async () => {
	const { reactive } = await import('vue')
	const state = reactive(shared.state)
	shared.state = state
	Object.assign(state, {
		phase: 'recording', recordingId: 'rec-1', startedAt: Date.now(),
		localChunks: 0, ackedChunks: 0, storageError: false, lowStorage: false,
		uploadOnline: true, uploadFailure: '', serverState: '', error: '',
		errorKind: '', micLost: false, micLostCause: '', captureInterrupted: false,
		interruptedSince: 0, interruptions: [], segment: 0,
	})
	return {
		clearSynchronizedRecordings: vi.fn(),
		readBatteryLevel: vi.fn().mockResolvedValue(undefined),
		RecorderEngine: class {
			state = state
			mediaStream = null
			start = vi.fn().mockResolvedValue(undefined)
			finish = (...a: unknown[]) => finish(...a)
			stop = vi.fn()
			retryNow = vi.fn()
			retrySync = vi.fn()
			recheckServerState = vi.fn()
		},
	}
})

const SESSION = {
	session_token: 'tok',
	table_number: 1,
	assembly: { id: 'a1', name: 'Bologna', language: 'en', recording_mode: 'orchestrated' },
	rounds: [{ id: 'round-1', position: 1, title: 'Mobility', status: 'CLOSED', duration_minutes: 30 }],
}
const ROUND = SESSION.rounds[0]

function statusWith(autoOrganized: boolean | undefined, reportAvailable: boolean) {
	return {
		assembly: { ...SESSION.assembly, auto_organized: autoOrganized },
		rounds: [{ ...ROUND, recorded_state: 'SYNCED' }],
		report_available: reportAvailable,
		assembly_closed: false,
	}
}

beforeEach(() => {
	vi.useFakeTimers()
	status.mockReset()
	Object.assign(shared.state, { phase: 'recording' })
})

async function mountDone() {
	const wrapper = mountWithI18n(RecordingScreen, { props: { session: SESSION, round: ROUND } })
	await flushPromises()
	Object.assign(shared.state, { phase: 'done' })
	await flushPromises()
	await vi.advanceTimersByTimeAsync(10100)
	return wrapper
}

describe('done screen of an automatic container', () => {
	it('tells the report is generated by itself', async () => {
		status.mockResolvedValue(statusWith(true, false))
		const wrapper = await mountDone()
		expect(wrapper.get('[data-test="auto-report-pending"]').text()).toContain('generated by itself')
	})

	it('says nothing of it for an ordinary session', async () => {
		status.mockResolvedValue(statusWith(false, false))
		const wrapper = await mountDone()
		expect(wrapper.find('[data-test="auto-report-pending"]').exists()).toBe(false)
	})

	it('drops the line once the report is available', async () => {
		status.mockResolvedValue(statusWith(true, true))
		const wrapper = await mountDone()
		expect(wrapper.find('[data-test="auto-report-pending"]').exists()).toBe(false)
	})
})
